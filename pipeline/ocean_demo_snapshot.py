def _native(rows: list[list], lats: list[float], lons: list[float]) -> dict:
    """row-major native arrays → {lat: {lon: value}} for ocean_grid._sample."""
    return {la: {lo: rows[r][c] for c, lo in enumerate(lons)}
            for r, la in enumerate(lats)}


