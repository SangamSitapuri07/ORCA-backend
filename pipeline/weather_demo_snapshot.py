def demo_payload() -> dict:
    """Snapshot in the same compact shape as GET /api/v1/weather/grid."""
    n_pts, frames = GRID_N * GRID_N, len(TIMES)
    u: list[list[float]] = [[] for _ in range(frames)]
    v: list[list[float]] = [[] for _ in range(frames)]
    rh: list[list] = [[] for _ in range(frames)]
    temp: list[list] = [[] for _ in range(frames)]
    pr: list[list] = [[] for _ in range(frames)]
    gust: list[list] = [[] for _ in range(frames)]
    cloud: list[list] = [[] for _ in range(frames)]
    for p in range(n_pts):
        for h in range(frames):
            s_ms = _S[p][h] / 3.6                     # km/h -> m/s
            th = math.radians(_D[p][h])
            u[h].append(round(-s_ms * math.sin(th), 2))
            v[h].append(round(-s_ms * math.cos(th), 2))
            rh[h].append(_RH[p][h])
            temp[h].append(_T[p][h])
            pr[h].append(_PR[p][h])
            gust[h].append(_G[p][h])
            cloud[h].append(_CL[p][h])
    lats_desc = [LATS[r] for r in range(GRID_N)]          # row lats, N→S
    lons_asc = list(LONS)                                  # col lons, W→E
    from pipeline.humidity import legend
    return {
        "type": "weather_grid",
        "demo": True,
        "fetched_at": FETCHED_AT,
        "model": "icon_global (DWD ICON global) via Open-Meteo — the model zoom.earth's humidity map displays",
        "source": SOURCE,
        "center": dict(CENTER),
        "span_deg": SPAN_DEG,
        "grid_n": GRID_N,
        "step_deg": round(SPAN_DEG / (GRID_N - 1), 4),
        "times": list(TIMES),
        "lats": lats_desc,
        "lons": lons_asc,
        "u": u,
        "v": v,
        "rh": rh,
        "temp": temp,
        "pr": pr,
        "gust": gust,
        "cloud": cloud,
        "legend": legend(),
    }
